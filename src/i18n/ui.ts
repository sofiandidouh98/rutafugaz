/** Prefijo de URL del idioma: '' para español, '/en' para inglés, etc. */
export function langPrefix(lang: Lang): string {
  return lang === defaultLang ? '' : `/${lang}`;
}

export function homePath(lang: Lang): string {
  return lang === defaultLang ? '/' : `/${lang}/`;
}

export function categoryPath(lang: Lang, cat: CategoryKey): string {
  return `${langPrefix(lang)}/${categorySlugs[lang][cat]}`;
}

/** El id de un post traducido es "en/slug"; el español es "slug". */
export function postLang(id: string): Lang {
  const first = id.split('/')[0] as Lang;
  return translatedLangs.includes(first as any) ? first : defaultLang;
}

export function postSlug(id: string): string {
  return postLang(id) === defaultLang ? id : id.split('/').slice(1).join('/');
}

export function postPath(id: string): string {
  return `${langPrefix(postLang(id))}/blog/${postSlug(id)}`;
}

